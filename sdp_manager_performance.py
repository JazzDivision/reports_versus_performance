"""**Pearson Correlation Coefficient** (correlation_coefficient) ranges between -1 and 1.

It represents the strength and direction of the linear relationship between two variables.

A positive coefficient indicates a positive linear relationship (as one variable increases, the other tends to increase), while a negative coefficient indicates a negative linear relationship (as one variable increases, the other tends to decrease).

A coefficient of 0 suggests no linear relationship.
"""

