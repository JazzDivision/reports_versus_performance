"""---
##**4️⃣ Fit the LR Model**
"""

# use `scikit-learn`:

from sklearn.linear_model import LinearRegression
import numpy as np

# Reshape X for sklearn
X = df[["No. Direct Reports"]]
y = df["H1 Performance %"]

model = LinearRegression()
model.fit(X, y)

"""---

## **5️⃣ Get the Equation of the Line**

"""

slope = model.coef_[0]
intercept = model.intercept_

print(f"y = {slope:.2f}x + {intercept:.2f}")

"""---

## **6️⃣ Make one prediction**

Now that you've trained your model, you can use it to predict the target based on the predictor.
"""

# Create a DataFrame with the new no. direct reports
new_data = pd.DataFrame({"No. Direct Reports": [1]})

# Predict the target % using the trained model
prediction = model.predict(new_data)  # This gives us a list with one predicted value

# Print the raw prediction result
print(prediction)

# Print the predicted % in a readable format
print(f"Predicted target performance based on no. direct reports: {prediction[0]:,.2f}%")

"""# **Evaluating the SRL Model**

Now that we've built a linear regression model and made predictions, it’s important to answer the question:

>**"How good is the model?"**

In other words — how well does the model’s predicted values match the actual data?

## **Why evaluate?**
Evaluation helps us:

- Understand if our model is reliable
- Detect underfitting or overfitting
- Compare different models or features

## **What are we evaluating?**

We're comparing:
- Actual values (from our dataset)
- Predicted values (from the model)

## **Key evaluation metrics for Linear Regression**

Here are the most common ways to evaluate a linear regression model:

| Metric                                   | Description                                                           | Evaluation                  |
|------------------------------------------|-----------------------------------------------------------------------|-----------------------------|
| **Mean Absolute Error (MAE)**            | Average of all absolute errors (easy to interpret)                    | The smaller the better      |
| **Root Mean Squared Error (RMSE)**       | Square root of MSE — brings error back to original units              | The smaller the better      |
| **R² Score (Coefficient of Determination)** | Measures how well the line fits the data (ranges from 0 to 1)         | The closer to 1, the better |

## **Let's evaluate our model**

Let's use the **training data** (`X` and `y`) to check how well the model fits it.

---
## **1️⃣  Loading the libraries**
"""

from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
import numpy as np

"""---
## **2️⃣ Predict on training data**
"""

# Get predictions on the training data
y_pred = model.predict(X)

"""---
## **3️⃣ Calculate the metrics**
"""

# Calculate evaluation metrics
mae = mean_absolute_error(y, y_pred)
rmse = np.sqrt(mean_squared_error(y, y_pred))
r2 = r2_score(y, y_pred)

"""---

## **4️⃣ Display the results**
"""

# Display the results
print(f"Mean Absolute Error (MAE): {mae:,.2f}%")
print(f"Root Mean Squared Error (RMSE): {rmse:,.2f}%")
print(f"R² Score: {r2:.4f}")

"""##  **6️⃣ Visualising actual vs predicted**


We can also **plot actual vs predicted** to see how well they line up. This step is optional, but helpful.
"""

import matplotlib.pyplot as plt
import seaborn as sns

plt.figure(figsize=(6,6))

sns.scatterplot(x=y, y=y_pred)
plt.plot([min(y), max(y)], [min(y), max(y)], color='red', linestyle='--')

plt.xlabel("Actual Values")
plt.ylabel("Predicted Values")
plt.title("Actual vs Predicted values")
plt.grid(True)
plt.show()

"""If your model is good, points will be close to the **diagonal line** (y = x).

## **Decide if the model is "Good"?**

- **Low error values** (MAE, RMSE)
- **High R² score** (close to 1)
- **Predictions follow the trend** shown in your data
"""

